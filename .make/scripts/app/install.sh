#!/usr/bin/env bash
# Installs the server's administration in one command: prerequisites, restic
# password and repository, alert of the nightly backup, first backup, then
# the nightly backup, the SMTP firewall and the weekly clean-up of Docker
# images. Safe to run again: what is already there is kept, done steps are
# skipped (asks for sudo).
#
# The restic password: kept if secrets/restic-password exists; asked when a
# restic repository is already there (a rebuild with the old backups put
# back in place, see docs/reconstruire-le-serveur.md), so that they stay
# readable; otherwise generated by make backup@init.
#
# @usage make app@install
set -euo pipefail
. "$(dirname "$0")/../lib.sh"

# Prerequisites: what the scripts below use.
for cmd in docker git make openssl curl systemctl sudo; do
  command -v "$cmd" >/dev/null || die "app@install : $cmd introuvable (voir Prérequis dans le README)"
done
docker info >/dev/null 2>&1 \
  || die "app@install : Docker inaccessible pour $(id -un) ; l'ajouter au groupe docker, puis se reconnecter"
info "Prérequis présents."

# A rebuild: the repository is there, its password must be the old one.
if [ ! -f "$BACKUP_PASSWORD_FILE" ] && sudo test -f "$BACKUP_REPOSITORY/config"; then
  cat <<MSG

  Un dépôt restic existe déjà ($BACKUP_REPOSITORY) : colle son mot de passe
  (gestionnaire de mots de passe), puis Entrée. Rien ne s'affiche pendant la saisie.

MSG
  read -r -s -p "  Mot de passe restic : " password
  printf '\n'
  [ -n "$password" ] || die "app@install : mot de passe vide ; sans lui, les sauvegardes existantes sont illisibles"
  mkdir -p "$(dirname "$BACKUP_PASSWORD_FILE")"
  ( umask 077 && printf '%s\n' "$password" > "$BACKUP_PASSWORD_FILE" )
  unset password
  if ! restic_run cat config >/dev/null 2>&1; then
    rm -f "$BACKUP_PASSWORD_FILE"
    die "app@install : ce mot de passe n'ouvre pas le dépôt $BACKUP_REPOSITORY"
  fi
  info "Mot de passe vérifié : les anciennes sauvegardes sont lisibles."
fi

"$SCRIPTS/backup/init.sh"

# Before the first backup, so that it already sends its signal.
if [ -f "$BACKUP_PING_FILE" ]; then
  info "Alerte de la sauvegarde déjà réglée ($BACKUP_PING_FILE)."
else
  "$SCRIPTS/backup/alert.sh"
fi

if restic_run snapshots --json 2>/dev/null | grep -q '"id"'; then
  info "Une sauvegarde existe déjà : pas de nouvelle sauvegarde maintenant."
else
  "$SCRIPTS/backup/run.sh"
fi

"$SCRIPTS/backup/schedule.sh"
"$SCRIPTS/firewall/install.sh"
"$SCRIPTS/firewall/test.sh"
"$SCRIPTS/docker/schedule.sh"

cat <<MSG

  Serveur prêt : sauvegarde chaque nuit, pare-feu SMTP, nettoyage Docker le dimanche.
  Vérifier : systemctl list-timers 'srv-*' --no-pager

MSG
