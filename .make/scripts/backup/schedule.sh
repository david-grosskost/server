#!/usr/bin/env bash
# Runs make backup@run each night, with a systemd timer: the service runs
# as the current user (who has Docker access), from this directory.
# Persistent: a night missed because the server was off is caught up at boot.
# Writes into /etc/systemd/system: asks for sudo. Safe to run again.
#
# @usage make backup@schedule
set -euo pipefail
. "$(dirname "$0")/../lib.sh"

command -v systemctl >/dev/null || die "backup@schedule : systemd introuvable (serveur Linux uniquement)"
[ -f "$BACKUP_PASSWORD_FILE" ] || die "backup@schedule : $BACKUP_PASSWORD_FILE absent → make backup@init"

make_bin="$(command -v make)"
user="$(id -un)"
units=/etc/systemd/system

sudo tee "$units/$BACKUP_UNIT.service" >/dev/null <<UNIT
# Generated by make backup@schedule ($PWD): do not edit, run it again.
[Unit]
Description=Sauvegarde de $BACKUP_SOURCE (restic)
Requires=docker.service
After=docker.service

[Service]
Type=oneshot
User=$user
WorkingDirectory=$PWD
ExecStart=$make_bin backup@run
UNIT

sudo tee "$units/$BACKUP_UNIT.timer" >/dev/null <<UNIT
# Generated by make backup@schedule ($PWD): do not edit, run it again.
[Unit]
Description=Sauvegarde nocturne de $BACKUP_SOURCE

[Timer]
OnCalendar=*-*-* 03:30
RandomizedDelaySec=15m
Persistent=true

[Install]
WantedBy=timers.target
UNIT

run sudo systemctl daemon-reload
run sudo systemctl enable --now "$BACKUP_UNIT.timer"
run systemctl list-timers "$BACKUP_UNIT.timer" --no-pager
info "Sauvegarde programmée chaque nuit vers 3 h 30. Journal : make backup@logs"
