#!/usr/bin/env bash
# Runs make docker@prune every week, with a systemd timer: Sunday morning,
# after the nightly backup. The service runs as the current user (who has
# Docker access), from this directory. Persistent: a run missed because the
# server was off is caught up at boot. Writes into /etc/systemd/system: asks
# for sudo. Safe to run again.
#
# @usage make docker@schedule
set -euo pipefail
. "$(dirname "$0")/../lib.sh"

command -v systemctl >/dev/null || die "docker@schedule : systemd introuvable (serveur Linux uniquement)"

make_bin="$(command -v make)"
user="$(id -un)"
units=/etc/systemd/system

sudo tee "$units/$DOCKER_UNIT.service" >/dev/null <<UNIT
# Generated by make docker@schedule ($PWD): do not edit, run it again.
[Unit]
Description=Nettoyage des images Docker inutiles
Requires=docker.service
After=docker.service

[Service]
Type=oneshot
User=$user
WorkingDirectory=$PWD
ExecStart=$make_bin docker@prune
UNIT

sudo tee "$units/$DOCKER_UNIT.timer" >/dev/null <<UNIT
# Generated by make docker@schedule ($PWD): do not edit, run it again.
[Unit]
Description=Nettoyage hebdomadaire des images Docker

[Timer]
OnCalendar=Sun *-*-* 04:30
RandomizedDelaySec=15m
Persistent=true

[Install]
WantedBy=timers.target
UNIT

run sudo systemctl daemon-reload
run sudo systemctl enable --now "$DOCKER_UNIT.timer"
run systemctl list-timers "$DOCKER_UNIT.timer" --no-pager
info "Nettoyage programmé chaque dimanche vers 4 h 30. Journal : make docker@logs"
