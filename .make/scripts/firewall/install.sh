#!/usr/bin/env bash
# Installs the outgoing SMTP firewall: a systemd service that applies it after
# each start of Docker (the rules do not survive a reboot or a restart of
# Docker), then applies it now. Writes into /etc/systemd/system: asks for
# sudo. Safe to run again.
#
# @usage make firewall@install
set -euo pipefail
. "$(dirname "$0")/../lib.sh"

command -v systemctl >/dev/null || die "firewall@install : systemd introuvable (serveur Linux uniquement)"
command -v iptables >/dev/null || die "firewall@install : iptables introuvable"

apply="$SCRIPTS/firewall/apply.sh"
units=/etc/systemd/system

sudo tee "$units/$FIREWALL_UNIT.service" >/dev/null <<UNIT
# Generated by make firewall@install ($PWD): do not edit, run it again.
[Unit]
Description=Pare-feu : SMTP sortant refusé aux conteneurs, sauf $FIREWALL_NETWORK
Requires=docker.service
After=docker.service
# Restarted with Docker, which rebuilds its own rules.
PartOf=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$apply
ExecStop=$apply --remove

[Install]
WantedBy=docker.service
UNIT

run sudo systemctl daemon-reload
run sudo systemctl enable "$FIREWALL_UNIT.service"
run sudo systemctl restart "$FIREWALL_UNIT.service"
"$SCRIPTS/firewall/status.sh"
info "Vérifier : make firewall@test"
