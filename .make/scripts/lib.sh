# Shared helpers for every make script. Sourced, never executed.
# shellcheck shell=bash
# Variables below are used by the scripts that source this file.
# shellcheck disable=SC2034

SCRIPTS="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Backups (make backup@*). Each setting can be overridden from the
# environment, e.g. BACKUP_SOURCE=/tmp/test make backup@run.
# restic runs in Docker: nothing to install on the server, same version everywhere.
RESTIC_IMAGE="${RESTIC_IMAGE:-restic/restic:0.19.1}"
# What is backed up, and the backup directory (excluded from the backup):
# the restic repository, and the restorations in progress (make backup@restore).
BACKUP_SOURCE="${BACKUP_SOURCE:-/srv}"
BACKUP_DIR="${BACKUP_DIR:-$BACKUP_SOURCE/backups}"
BACKUP_REPOSITORY="${BACKUP_REPOSITORY:-$BACKUP_DIR/restic}"
BACKUP_RESTORE_DIR="${BACKUP_RESTORE_DIR:-$BACKUP_DIR/restore}"
# SuiteCRM instances (make backup@restore): one directory per instance.
SUITECRM_DIR="${SUITECRM_DIR:-$BACKUP_SOURCE/suitecrm}"
# Kept snapshots: the last 7 days, then 1 per week for 4 weeks, then 1 per month for 12 months.
BACKUP_KEEP_DAILY="${BACKUP_KEEP_DAILY:-7}"
BACKUP_KEEP_WEEKLY="${BACKUP_KEEP_WEEKLY:-4}"
BACKUP_KEEP_MONTHLY="${BACKUP_KEEP_MONTHLY:-12}"
# Relative to the project: the password is generated by make backup@init.
BACKUP_PASSWORD_FILE="secrets/restic-password"
# Database dumps, made before each backup and saved with it.
BACKUP_DUMP_DIR="data/dumps"
# restic's local cache (speeds up the backups, rebuilt if deleted).
BACKUP_CACHE_DIR="data/restic-cache"
# systemd service and timer of the nightly backup (make backup@schedule).
BACKUP_UNIT="srv-backup"

# Prints an error and exits.
#
# @param string $* Message
die () { printf '%s\n' "$*" >&2; exit 1; }

# Prints an indented message.
#
# @param string $* Message
info () { printf '  %s\n' "$*"; }

# Prints a command, then runs it.
#
# @param string $@ Command and arguments
run () {
  local arg shown=()
  for arg in "$@"; do
    case $arg in *[[:space:]]*) shown+=("\"$arg\"") ;; *) shown+=("$arg") ;; esac
  done
  printf '  \033[2m%s\033[0m\n' "${shown[*]}"
  "$@"
}

# Extra docker run arguments of the next restic_run calls (e.g. a mount).
RESTIC_DOCKER_ARGS=()

# Runs restic in Docker, on the repository of BACKUP_REPOSITORY.
# The source is mounted read-only at the same path, so snapshots show the
# real paths (/srv/...). The container takes the machine's name: restic
# groups snapshots by host.
#
# @param string $@ restic arguments
restic_run () {
  [ -f "$BACKUP_PASSWORD_FILE" ] \
    || die "restic : $BACKUP_PASSWORD_FILE absent → make backup@init"
  mkdir -p "$BACKUP_CACHE_DIR"
  run docker run --rm \
    --hostname "$(hostname)" \
    -v "$BACKUP_SOURCE:$BACKUP_SOURCE:ro" \
    -v "$BACKUP_REPOSITORY:/repo" \
    -v "$PWD/$BACKUP_CACHE_DIR:/cache" \
    -v "$PWD/$BACKUP_PASSWORD_FILE:/run/secrets/restic-password:ro" \
    -e RESTIC_REPOSITORY=/repo \
    -e RESTIC_PASSWORD_FILE=/run/secrets/restic-password \
    -e RESTIC_CACHE_DIR=/cache \
    "${RESTIC_DOCKER_ARGS[@]}" \
    "$RESTIC_IMAGE" "$@"
}
